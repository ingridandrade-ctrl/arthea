// Palavras-chave que disparam handoff IMEDIATO (sem passar pela IA).
// Removido "preço/valor/orçamento" — esses a Ingrid AI sabe responder
// agora (tem os valores oficiais no prompt). Só transfere em sinais
// fortes de fechamento ou negociação.
export const HANDOFF_KEYWORDS = [
  "falar com alguém",
  "falar com humano",
  "falar com pessoa",
  "falar com atendente",
  "atendente",
  "pessoa real",
  "contrato",
  "fechar",
  "contratar",
  "assinar",
  "começar agora",
  "desconto",
  "condição especial",
  "parcelar em mais",
];

export function shouldHandoff(message: string, keywords?: string[]): boolean {
  const lower = message.toLowerCase();
  const list = keywords && keywords.length > 0 ? keywords : HANDOFF_KEYWORDS;
  return list.some((keyword) => lower.includes(keyword));
}
